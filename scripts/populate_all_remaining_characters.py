def populate_remaining_characters() -> int:
    con = sqlite3.connect("club_romance.db")
    cur = con.cursor()

    inserted = 0
    for ch in ALL_REMAINING_CHARACTERS:
        story_id = ch["story_id"]
        # Check if character already exists for this story with this name
        cur.execute("SELECT id FROM characters WHERE story_id = ? AND name = ?", (story_id, ch["name"]))
        if cur.fetchone():
            continue

        cur.execute(
            """
            INSERT INTO characters (story_id, name, description, status, is_love_interest, spoiler_level, facts)
            VALUES (?, ?, ?, ?, ?, 0, ?);
            """,
            (
                story_id,
                ch["name"],
                ch["description"],
                ch["status"],
                1 if ch["is_love_interest"] else 0,
                ch["facts"],
            ),
        )
        inserted += 1

    con.commit()
    print(f"Inserted {inserted} characters across remaining stories.")

    # Check total characters and stories with characters
    cur.execute("SELECT count(*) FROM characters;")
    total_chars = cur.fetchone()[0]

    cur.execute("SELECT count(DISTINCT story_id) FROM characters;")
    stories_with_chars = cur.fetchone()[0]

    cur.execute("SELECT count(*) FROM stories;")
    total_stories = cur.fetchone()[0]

    print(f"Total characters now: {total_chars}")
    print(f"Stories with characters: {stories_with_chars} / {total_stories}")

    con.close()
    return inserted


if __name__ == "__main__":
    populate_remaining_characters()
