def run_migration():
    conn = sqlite3.connect('club_romance.db')
    cursor = conn.cursor()

    print("Beginning canon characters update...")

    # Verify stories exist
    cursor.execute("SELECT id, title FROM stories")
    existing_stories = {r[0]: r[1] for r in cursor.fetchall()}
    print(f"Total stories in DB: {len(existing_stories)}")

    # Clear current characters table
    cursor.execute("DELETE FROM characters")
    print("Cleared old characters table.")

    # Reset autoincrement for characters if table exists
    try:
        cursor.execute("DELETE FROM sqlite_sequence WHERE name = 'characters'")
    except sqlite3.OperationalError:
        pass

    total_inserted = 0

    for story_id, char_list in CANON_CHARACTERS.items():
        if story_id not in existing_stories:
            print(f"WARNING: Story ID {story_id} not found in stories table! Skipping.")
            continue

        story_title = existing_stories[story_id]

        for char in char_list:
            cursor.execute("""
                INSERT INTO characters (
                    story_id,
                    name,
                    description,
                    status,
                    is_love_interest,
                    spoiler_level,
                    facts
                ) VALUES (?, ?, ?, ?, ?, ?, ?)
            """, (
                story_id,
                char["name"],
                char["description"],
                char["status"],
                1 if char["is_love_interest"] else 0,
                char.get("spoiler_level", 0),
                char["facts"]
            ))
            total_inserted += 1

    conn.commit()

    # Integrity and FK checks
    cursor.execute("PRAGMA integrity_check")
    integrity = cursor.fetchone()[0]
    cursor.execute("PRAGMA foreign_key_check")
    fks = cursor.fetchall()

    print(f"Update completed successfully! Total characters inserted: {total_inserted}")
    print(f"PRAGMA integrity_check: {integrity}")
    print(f"PRAGMA foreign_key_check: {fks} (empty list means 0 violations)")

    # Summary by story
    cursor.execute("""
        SELECT s.id, s.title, COUNT(c.id)
        FROM stories s
        LEFT JOIN characters c ON s.id = c.story_id
        GROUP BY s.id
        ORDER BY s.id
    """)
    rows = cursor.fetchall()
    print("\nSummary per story:")
    for sid, title, cnt in rows:
        print(f"  [{sid:2d}] {title}: {cnt} characters")

    conn.close()

if __name__ == '__main__':
    run_migration()
