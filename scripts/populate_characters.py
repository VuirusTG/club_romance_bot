def populate_characters(db_path: Path = Path("club_romance.db")) -> int:
    if not db_path.exists():
        raise FileNotFoundError(f"Database {db_path} not found.")

    pre_sha = compute_sha256(db_path)
    ts = datetime.now().strftime("%Y%m%d_%H%M%S")
    backup_path = db_path.parent / f"club_romance_before_chars_{ts}.db"
    shutil.copy2(db_path, backup_path)
    assert compute_sha256(backup_path) == pre_sha
    print(f"[OK] Verified backup created: {backup_path}")

    conn = sqlite3.connect(db_path)
    cur = conn.cursor()

    try:
        cur.execute("BEGIN TRANSACTION;")

        # Clear existing table if any
        cur.execute("DELETE FROM characters;")

        # Insert characters
        inserted_count = 0
        for ch in CHARACTERS_DATA:
            story_id = ch["story_id"]
            # Verify story exists
            cur.execute("SELECT id FROM stories WHERE id = ?", (story_id,))
            if not cur.fetchone():
                print(f"[WARN] Story ID {story_id} not found, skipping {ch['name']}")
                continue

            cur.execute(
                """
                INSERT INTO characters 
                    (story_id, name, description, status, is_love_interest, spoiler_level, facts)
                VALUES (?, ?, ?, ?, ?, 0, ?);
                """,
                (
                    story_id,
                    ch["name"],
                    ch["description"],
                    ch["status"],
                    1 if ch["is_love_interest"] else 0,
                    ch.get("facts", ""),
                ),
            )
            inserted_count += 1

        cur.execute("COMMIT;")
        print(f"[OK] Successfully inserted {inserted_count} characters across stories.")

    except Exception as e:
        cur.execute("ROLLBACK;")
        conn.close()
        raise RuntimeError(f"Character population failed: {e}")

    # Verify integrity and foreign keys
    cur.execute("PRAGMA integrity_check;")
    assert cur.fetchone()[0] == "ok"
    cur.execute("PRAGMA foreign_key_check;")
    assert len(cur.fetchall()) == 0

    # Verify count
    cur.execute("SELECT count(*) FROM characters;")
    total_in_db = cur.fetchone()[0]
    assert total_in_db == inserted_count
    print(f"[OK] Total characters in DB now: {total_in_db}")

    conn.close()
    return total_in_db


