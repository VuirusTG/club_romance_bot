def _fetch_lore_from_database(title: str, genre: str = "") -> StoryLore | None:
    """Extract real character data and setting directly from SQLite database."""
    db_path = Path(__file__).resolve().parents[3] / "club_romance.db"
    if not db_path.exists():
        return None

    try:
        conn = sqlite3.connect(db_path)
        c = conn.cursor()
        c.execute("SELECT id, title, genre FROM stories")
        stories = c.fetchall()

        matched = [s for s in stories if title.lower() in s[1].lower() or s[1].lower() in title.lower()]
        if not matched:
            conn.close()
            return None

        story_id, db_title, db_genre = matched[0]
        c.execute("SELECT name, description, is_love_interest, status FROM characters WHERE story_id=?", (story_id,))
        chars = c.fetchall()
        conn.close()

        if not chars:
            return None

        heroine_rows = [ch for ch in chars if not ch[2]]
        heroine_name = heroine_rows[0][0] if heroine_rows else "Главная героиня"
        heroine_desc = heroine_rows[0][1] if heroine_rows else ""
        heroine_str = f"{heroine_name} ({heroine_desc})" if heroine_desc else heroine_name

        love_interests = [ch[0] for ch in chars if ch[2]]

        # Query thematic wiki for authentic tagline and synopsis (without citing sources)
        wiki = ThematicResearcher.fetch_story_lore(db_title)
        synopsis = wiki.synopsis if wiki and wiki.synopsis else ""
        tagline = wiki.tagline if wiki and wiki.tagline else ""

        setting = synopsis[:200] if synopsis else f"Сеттинг новеллы «{db_title}» ({db_genre})"
        pitch = tagline if tagline else (f"Увлекательная история «{db_title}» ({db_genre}). Пройдите путь героини {heroine_name} без сюжетных ошибок!")
        conflict = heroine_desc if heroine_desc else f"Судьбоносные решения и сложные развилки в новелле «{db_title}»"

        stats = list(CANONICAL_STAT_PATHS.get(db_title, ("Путь Разума", "Путь Чувств")))

        return StoryLore(
            title=db_title,
            genre=db_genre or genre,
            setting=setting,
            heroine=heroine_str,
            core_conflict=conflict,
            atmosphere_tags=[db_title, "Клуб Романтики", db_genre],
            popular_tropes=["ветки с фаворитами", "сюжетные выборы", "интерактивный гайд"],
            key_favorites=love_interests,
            stat_paths=stats,
            compelling_pitch=pitch,
            dramatic_dilemma=f"Сможет ли {heroine_name} сделать верный выбор на решающей развилке сюжета?",
        )
    except Exception as e:
        logger.debug(f"DB lore extraction failed: {e}")
        return None


def get_story_lore(title: str, genre: str = "") -> StoryLore:
    """
    Return 100% authentic, canonical lore for a story.
    Strictly NO hallucinated or fictional characters.
    Uses curated database, SQLite characters database, and thematic encyclopedia.
    """
    # 1. Direct match in curated database
    if title in STORY_LORE_DATABASE:
        return STORY_LORE_DATABASE[title]

    # 2. Case-insensitive / partial match in curated database
    for st_title, lore in STORY_LORE_DATABASE.items():
        if st_title.lower() == title.lower() or st_title.lower() in title.lower() or title.lower() in st_title.lower():
            return lore

    # 3. Query SQLite database for genuine characters and story info
    db_lore = _fetch_lore_from_database(title, genre)
    if db_lore:
        return db_lore

    # 4. If story not in DB, use ThematicResearcher for authentic facts without citations
    wiki_data = ThematicResearcher.fetch_story_lore(title)
    if wiki_data and (wiki_data.synopsis or wiki_data.tagline):
        pitch = wiki_data.tagline or wiki_data.synopsis[:200]
        return StoryLore(
            title=title,
            genre=wiki_data.genre or genre or "Визуальная новелла",
            setting=f"Сеттинг новеллы «{title}»: {wiki_data.synopsis[:180]}",
            heroine=f"Главная героиня новеллы «{title}»",
            core_conflict=wiki_data.synopsis[:200] if wiki_data.synopsis else f"Сюжетные развилки новеллы «{title}»",
            atmosphere_tags=[title, "Клуб Романтики", wiki_data.genre or "новелла"],
            popular_tropes=["развилки сюжета", "выборы и последствия"],
            key_favorites=[],
            stat_paths=list(CANONICAL_STAT_PATHS.get(title, ("Путь Разума", "Путь Чувств"))),
            compelling_pitch=pitch,
            dramatic_dilemma=f"Сложные развилки и цена каждого решения в новелле «{title}».",
        )

    # 5. Last resort without inventing characters
    stat_pair = CANONICAL_STAT_PATHS.get(title, ("Путь Разума", "Путь Чувств"))
    return StoryLore(
        title=title,
        genre=genre or "Визуальная новелла",
        setting=f"Оригинальный сеттинг новеллы «{title}» в Клубе Романтики",
        heroine=f"Главная героиня новеллы «{title}»",
        core_conflict=f"Ключевые сюжетные развилки и выборы в истории «{title}»",
        atmosphere_tags=["Клуб Романтики", title, "романтика"],
        popular_tropes=["сюжетные развилки", "выборы и последствия"],
        key_favorites=[],
        stat_paths=list(stat_pair),
        compelling_pitch=f"Захватывающая история «{title}» в Клубе Романтики. Погрузитесь в сюжет и открывайте лучшие сцены с интерактивным гайдом бота!",
        dramatic_dilemma=f"Какой выбор станет решающим в судьбе героев «{title}»?",
    )
