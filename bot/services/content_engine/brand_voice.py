def build_user_prompt(
    topic: str,
    main_point: str,
    facts: str = "",
    cta: str = "",
    target_story: str = "",
) -> str:
    parts = [
        f"Тема: {topic}",
        f"Основная мысль: {main_point}",
    ]
    if facts:
        parts.append(f"Факты / условия: {facts}")
    if cta:
        parts.append(f"Призыв к действию (CTA): {cta}")
    if target_story:
        parts.append(f"Целевая новелла / история: {target_story}")

    parts.append(
        "\nСгенерируй ответ строго в формате JSON со следующими ключами:\n"
        "{\n"
        '  "telegram": "Текст для Telegram",\n'
        '  "vk": "Текст для VK",\n'
        '  "instagram": "Текст для Instagram",\n'
        '  "threads": "Текст для Threads",\n'
        '  "image_prompt": "Промпт для изображения на английском языке"\n'
        "}"
    )
    return "\n".join(parts)
